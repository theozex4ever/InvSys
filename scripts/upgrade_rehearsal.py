def write_fixture(target: Path = FIXTURE) -> None:
    """Regenerate the committed SQL text; a maintainer reviews the diff like evidence."""
    with tempfile.TemporaryDirectory(prefix="invsys-fixture-") as scratch:
        database = Path(scratch) / "inventory.db"
        build_fixture_database(database)
        with closing(sqlite3.connect(database)) as connection:
            dump = [
                line
                for line in connection.iterdump()
                if line not in ("BEGIN TRANSACTION;", "COMMIT;")
            ]
    # SQLAlchemy creates indexes in set order; sorting keeps the committed text reproducible.
    indexes = sorted(line for line in dump if line.startswith("CREATE INDEX"))
    statements = [line for line in dump if not line.startswith("CREATE INDEX")] + indexes
    target.parent.mkdir(parents=True, exist_ok=True)
    revision = package_bundle.source_revision(ROOT)
    provenance = f"-- Written by the application at commit {revision.get('commit', 'unknown')}."
    target.write_text(
        "\n".join([FIXTURE_HEADER, provenance, *statements]) + "\n", encoding="utf-8", newline="\n"
    )


def fixture_sha256(fixture: Path = FIXTURE) -> str:
    """Hash of the fixture text with line endings normalized (a Windows checkout may add CRs)."""
    return hashlib.sha256(fixture.read_text(encoding="utf-8").encode("utf-8")).hexdigest()


def install_fixture(target: Path, fixture: Path = FIXTURE) -> None:
    """Create a disposable copy of the pre-migration inventory at ``target``."""
    if target.exists():
        raise RehearsalError(f"Refusing to overwrite {target}.")
    target.parent.mkdir(parents=True, exist_ok=True)
    script = fixture.read_text(encoding="utf-8")
    if not script.startswith(FIXTURE_HEADER):
        raise RehearsalError(f"{fixture} is not a pre-migration fixture.")
    with closing(sqlite3.connect(target)) as connection:
        connection.executescript(script)


# ----------------------------------------------------------------- snapshots


@contextmanager
def _scratch_copy(database: Path) -> Iterator[Path]:
    """A throwaway copy of the database with its WAL sidecars, so reading never changes it."""
    with tempfile.TemporaryDirectory(prefix="invsys-snapshot-") as scratch:
        copy = Path(scratch) / "inventory.db"
        for suffix in ("", "-wal", "-shm"):
            source = database.with_name(database.name + suffix)
            if source.is_file():
                shutil.copy2(source, copy.with_name(copy.name + suffix))
        yield copy


def snapshot(database: Path) -> dict[str, Any]:
    """Schema, integrity and every row of the operational tables, keyed by primary key."""
    with _scratch_copy(database) as copy, closing(sqlite3.connect(copy)) as connection:
        integrity = str(connection.execute("PRAGMA integrity_check").fetchone()[0])
        foreign_keys = connection.execute("PRAGMA foreign_key_check").fetchall()
        schema = [
            list(row)
            for row in connection.execute(
                "SELECT type, name, tbl_name, sql FROM sqlite_master "
                "WHERE name NOT LIKE 'sqlite_%' ORDER BY type, name"
            )
        ]
        tables: dict[str, Any] = {}
        for table in TABLES:
            # Fixed table names, never operator input.
            cursor = connection.execute(f"SELECT * FROM {table} ORDER BY 1")  # noqa: S608
            columns = [column[0] for column in cursor.description]
            tables[table] = {
                "columns": columns,
                "rows": {str(row[0]): list(row) for row in cursor.fetchall()},
            }
    return {
        "integrity_check": integrity,
        "foreign_key_violations": len(foreign_keys),
        "schema": schema,
        "tables": tables,
    }


def digest(state: dict[str, Any]) -> str:
    """Stable fingerprint of a snapshot (schema and rows)."""
    canonical = json.dumps(
        {"schema": state["schema"], "tables": state["tables"]},
        sort_keys=True,
        separators=(",", ":"),
    )
    return hashlib.sha256(canonical.encode("utf-8")).hexdigest()


def counts(state: dict[str, Any]) -> dict[str, int]:
    return {table: len(state["tables"][table]["rows"]) for table in TABLES}


def compare(
    before: dict[str, Any],
    after: dict[str, Any],
    *,
    identical: bool,
    stock_moved: bool = False,
) -> list[str]:
    """Differences that must not exist, as readable problems (empty means preserved).

    ``identical`` demands the same schema and rows. Otherwise every ``before`` row must
    survive unchanged in ``after`` (which may hold more), except the preferences the
    application is allowed to rewrite. ``stock_moved`` also lets existing Stock balances
    differ, for work that posted new ledger rows against them (``reconcile`` then proves
    each balance still equals its ledger).
    """
    problems: list[str] = []
    if before["schema"] != after["schema"]:
        problems.append("The schema changed.")
    if after["integrity_check"] != "ok":
        problems.append(f"SQLite integrity check: {after['integrity_check']}.")
    if after["foreign_key_violations"]:
        problems.append(f"{after['foreign_key_violations']} foreign key violation(s).")
    for table in TABLES:
        old, new = before["tables"][table]["rows"], after["tables"][table]["rows"]
        columns = before["tables"][table]["columns"]
        for key, row in old.items():
            if key not in new:
                problems.append(f"{table} row {key} is missing.")
            elif new[key][: len(row)] != row and not (
                (table == "settings" and key in PREFERENCE_KEYS and not identical)
                or (table == "inventory_balances" and stock_moved)
            ):
                changed = [
                    column
                    for column, was, now in zip(columns, row, new[key], strict=False)
                    if was != now
                ]
                problems.append(f"{table} row {key} changed ({', '.join(changed)}).")
        if identical:
            problems.extend(f"{table} row {key} is new." for key in new if key not in old)
    return problems


def _table(state: dict[str, Any], table: str) -> list[dict[str, Any]]:
    columns = state["tables"][table]["columns"]
    return [dict(zip(columns, row, strict=True)) for row in state["tables"][table]["rows"].values()]


def reconcile(state: dict[str, Any]) -> list[str]:
    """Check the ledger invariants: balances equal the ledger, shipments equal their rows."""
    problems: list[str] = []
    transactions = _table(state, "inventory_transactions")
    posted: dict[tuple[int, int, int], int] = {}
    for row in transactions:
        if row["lot_id"] is None:
            continue
        location = row["location_from_id"] if row["quantity_change"] < 0 else row["location_to_id"]
        key = (row["part_id"], row["lot_id"], location)
        posted[key] = posted.get(key, 0) + row["quantity_change"]
    balances = {
        (row["part_id"], row["lot_id"], row["location_id"]): row["quantity"]
        for row in _table(state, "inventory_balances")
    }
    for key in sorted(posted.keys() | balances.keys()):
        if posted.get(key, 0) != balances.get(key, 0):
            problems.append(
                f"Balance part/lot/location {key} is {balances.get(key, 0)} "
                f"but the ledger posts {posted.get(key, 0)}."
            )
        if balances.get(key, 0) < 0:
            problems.append(f"Balance part/lot/location {key} is negative.")
    components = _table(state, "shipment_components")
    for shipment in _table(state, "shipments"):
        rows = [row for row in transactions if row["shipment_id"] == shipment["id"]]
        number = shipment["shipment_number"]
        mine = [row for row in components if row["shipment_id"] == shipment["id"]]
        if not mine:
            shipped = -sum(row["quantity_change"] for row in rows if row["tx_type"] == "SHIP")
            if shipped != shipment["quantity"]:
                problems.append(f"Shipment {number} shipped {shipped}, not {shipment['quantity']}.")
            continue
        phantom = -sum(row["quantity_change"] for row in rows if row["tx_type"] == "SHIP_BOM")
        if phantom != shipment["quantity"]:
            problems.append(
                f"Shipment {number} records {phantom} assemblies, not {shipment['quantity']}."
            )
        snapshot_by_key: dict[tuple[int, int, int], int] = {}
        for row in mine:
            key = (row["part_id"], row["lot_id"], row["location_id"])
            snapshot_by_key[key] = snapshot_by_key.get(key, 0) + row["quantity"]
        consumed: dict[tuple[int, int, int], int] = {}
        for row in rows:
            if row["tx_type"] == "BOM_CONSUME":
                key = (row["part_id"], row["lot_id"], row["location_from_id"])
                consumed[key] = consumed.get(key, 0) - row["quantity_change"]
        if snapshot_by_key != consumed:
            problems.append(
                f"Shipment {number} component snapshot differs from its consumption rows."
            )
    return problems


def component_trace(state: dict[str, Any]) -> dict[str, list[list[Any]]]:
    """Per-shipment component snapshots by natural keys (Part, Lot, Location, quantity)."""
    parts = {row["id"]: row["part_number"] for row in _table(state, "parts")}
    lots = {row["id"]: row["lot_number"] for row in _table(state, "lots")}
    locations = {row["id"]: row["name"] for row in _table(state, "locations")}
    numbers = {row["id"]: row["shipment_number"] for row in _table(state, "shipments")}
    trace: dict[str, list[list[Any]]] = {}
    for row in _table(state, "shipment_components"):
        trace.setdefault(numbers[row["shipment_id"]], []).append(
            [
                parts[row["part_id"]],
                lots[row["lot_id"]],
                locations[row["location_id"]],
                row["quantity"],
            ]
        )
    return {number: sorted(lines) for number, lines in sorted(trace.items())}


def dropped_entries(kept: dict[str, Any], replaced: dict[str, Any]) -> dict[str, Any]:
    """Ledger entries and shipments in ``replaced`` that ``kept`` lacks (to reconcile by hand)."""
    transactions = [
        row
        for key, row in replaced["tables"]["inventory_transactions"]["rows"].items()
        if key not in kept["tables"]["inventory_transactions"]["rows"]
    ]
    shipments = [
        row[1]
        for key, row in replaced["tables"]["shipments"]["rows"].items()
        if key not in kept["tables"]["shipments"]["rows"]
    ]
    by_type: dict[str, int] = {}
    for row in transactions:
        by_type[row[2]] = by_type.get(row[2], 0) + 1
    return {
        "ledger_entries": len(transactions),
        "ledger_entry_ids": [row[0] for row in transactions],
        "by_type": dict(sorted(by_type.items())),
        "shipments": sorted(shipments),
    }


# ------------------------------------------------------------------- restore


def _sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def check_backup(path: Path) -> None:
    """Refuse anything that is not a readable, intact inventory file."""
    if not path.exists():
        raise RestoreRefused(f"The backup {path} does not exist. Nothing was changed.")
    if not path.is_file():
        raise RestoreRefused(f"The backup {path} is not a file. Nothing was changed.")
    try:
        # immutable=1: checking a backup must not create WAL sidecars beside it.
        with closing(sqlite3.connect(f"{path.as_uri()}?mode=ro&immutable=1", uri=True)) as copy:
            result = copy.execute("PRAGMA quick_check").fetchall()
            tables = {row[0] for row in copy.execute("SELECT name FROM sqlite_master")}
    except sqlite3.Error as exc:
        raise RestoreRefused(
            f"The backup {path.name} is not a usable SQLite inventory ({exc}). Nothing was changed."
        ) from exc
    if result != [("ok",)]:
        raise RestoreRefused(
            f"The backup {path.name} failed its integrity check. Nothing was changed."
        )
    missing = [table for table in REQUIRED_TABLES if table not in tables]
    if missing:
        raise RestoreRefused(
            f"The file {path.name} is not an InvSys inventory (no {', '.join(missing)} table). "
            "Nothing was changed."
        )


def restore_from_backup(
    database: Path,
    backup: Path,
    aside_root: Path,
    *,
    stamp: str | None = None,
    after_aside: Callable[[], None] | None = None,
) -> dict[str, Any]:
    """The documented closed-app restore, step by step, with the application closed.

    The current database (and its WAL sidecars) is moved into a new folder under
    ``aside_root``, never deleted. The backup is copied beside the database, verified,
    then renamed into place. Any failure puts the moved files back and raises
    ``RestoreRefused``. ``after_aside`` lets a test inject a failure between the steps.
    """
    check_backup(backup)
    if database.exists() and database.resolve() == backup.resolve():
        raise RestoreRefused("The backup is the live database itself. Nothing was changed.")
    aside = aside_root / f"restore-aside-{stamp or datetime.now().strftime(STAMP_FORMAT)}"
    try:
        aside.mkdir(parents=True)
    except OSError as exc:
        raise RestoreRefused(
            f"Cannot create the aside folder {aside}: {exc.strerror or exc}. Nothing was changed."
        ) from exc
    moved: list[tuple[Path, Path]] = []
    staged = database.with_name(database.name + ".restoring")
    try:
        for suffix in ("", "-wal", "-shm"):
            source = database.with_name(database.name + suffix)
            if source.exists():
                destination = aside / source.name
                source.replace(destination)
                moved.append((source, destination))
        if after_aside is not None:
            after_aside()
        shutil.copyfile(backup, staged)
        check_backup(staged)
        staged.replace(database)
    except (OSError, RestoreRefused) as exc:
        staged.unlink(missing_ok=True)
        undone = _put_back(moved)
        if undone:
            with suppress(OSError):
                aside.rmdir()
        reason = exc.strerror or exc if isinstance(exc, OSError) else exc
        raise RestoreRefused(
            f"Restore failed: {reason}. "
            + (
                "The previous database was put back; nothing was changed."
                if undone
                else f"The previous database could NOT be put back; it is in {aside}."
            )
        ) from exc
    if not any(aside.iterdir()):
        aside.rmdir()
    return {
        "restored_from": backup.name,
        "backup_sha256": _sha256(backup),
        "aside_directory": str(aside),
        "kept_aside": sorted(item.name for item in aside.iterdir()) if aside.exists() else [],
    }


def _put_back(moved: list[tuple[Path, Path]]) -> bool:
    restored = True
    for original, aside in reversed(moved):
        try:
            aside.replace(original)
        except OSError:
            restored = False
    return restored


def restore_failure_probes(scratch: Path) -> list[dict[str, Any]]:
    """Run the restore against refusals and file failures, recording each actual message."""
    probes: list[dict[str, Any]] = []

    def prepare(name: str) -> tuple[Path, Path, Path]:
        folder = scratch / name
        database = folder / "inventory.db"
        install_fixture(database)
        good = folder / "backups" / "inventory-good.db"
        good.parent.mkdir()
        with closing(sqlite3.connect(database)) as source, closing(sqlite3.connect(good)) as copy:
            source.backup(copy)
        return database, good, folder / "restore-aside"

    def probe(
        name: str,
        action: Callable[[Path, Path, Path], None],
        expected: str,
        applicable: bool = True,
    ) -> None:
        if not applicable:
            probes.append({"name": name, "applicable": False, "passed": True})
            return
        database, good, aside_root = prepare(name)
        before = _sha256(database)
        message = ""
        try:
            action(database, good, aside_root)
        except RestoreRefused as exc:
            message = str(exc)
        probes.append(
            {
                "name": name,
                "applicable": True,
                "message": message,
                "database_untouched": database.is_file() and _sha256(database) == before,
                "no_partial_files": not database.with_name("inventory.db.restoring").exists()
                and not any(aside_root.glob("*/inventory.db")),
                "passed": expected in message
                and database.is_file()
                and _sha256(database) == before
                and not database.with_name("inventory.db.restoring").exists()
                and not any(aside_root.glob("*/inventory.db")),
            }
        )

    def missing(database: Path, good: Path, aside_root: Path) -> None:
        restore_from_backup(database, good.with_name("absent.db"), aside_root)

    def garbage(database: Path, good: Path, aside_root: Path) -> None:
        bad = good.with_name("inventory-garbage.db")
        bad.write_text("not an SQLite database", encoding="utf-8")
        restore_from_backup(database, bad, aside_root)

    def truncated(database: Path, good: Path, aside_root: Path) -> None:
        bad = good.with_name("inventory-truncated.db")
        bad.write_bytes(good.read_bytes()[: good.stat().st_size // 2 + 7])
        restore_from_backup(database, bad, aside_root)

    def foreign(database: Path, good: Path, aside_root: Path) -> None:
        other = good.with_name("inventory-other.db")
        with closing(sqlite3.connect(other)) as connection:
            connection.execute("CREATE TABLE unrelated (id INTEGER PRIMARY KEY)")
        restore_from_backup(database, other, aside_root)

    def itself(database: Path, _good: Path, aside_root: Path) -> None:
        restore_from_backup(database, database, aside_root)

    def aside_blocked(database: Path, good: Path, aside_root: Path) -> None:
        aside_root.write_text("a file where the aside folder belongs", encoding="utf-8")
        restore_from_backup(database, good, aside_root)

    def locked_database(database: Path, good: Path, aside_root: Path) -> None:
        # Windows refuses to rename a file another process holds open (the application
        # still running); POSIX systems do not, which is why the procedure says "close".
        with database.open("rb"):
            restore_from_backup(database, good, aside_root)

    def read_only_folder(database: Path, good: Path, _aside_root: Path) -> None:
        folder = database.parent
        folder.chmod(0o500)
        try:
            # The aside folder lives outside the read-only folder, so the rename is what fails.
            restore_from_backup(database, good, folder.parent / "aside-elsewhere")
        finally:
            folder.chmod(0o700)

    def copy_fails(database: Path, good: Path, aside_root: Path) -> None:
        def fail() -> None:
            raise OSError(28, "No space left on device")

        restore_from_backup(database, good, aside_root, after_aside=fail)

    probe("backup-does-not-exist", missing, "does not exist")
    probe("backup-is-not-sqlite", garbage, "not a usable SQLite inventory")
    probe("backup-is-truncated", truncated, "Nothing was changed")
    probe("backup-is-another-kind-of-database", foreign, "is not an InvSys inventory")
    probe("backup-is-the-live-database", itself, "live database itself")
    probe("aside-folder-cannot-be-created", aside_blocked, "Cannot create the aside folder")
    probe("copy-fails-after-database-moved-aside", copy_fails, "put back")
    posix_writable = os.name == "posix" and os.geteuid() != 0
    probe("database-folder-is-read-only", read_only_folder, "Restore failed", posix_writable)
    probe(
        "database-held-open-by-another-program",
        locked_database,
        "Restore failed",
        sys.platform == "win32",
    )
    return probes


# --------------------------------------------------------------- the rehearsal


class Launcher:
    """The application under rehearsal: a frozen bundle or a source launch."""

    def __init__(self, bundle: Path | None, isolate_network: bool) -> None:
        self.bundle = bundle
        self.isolate_network = isolate_network

    def run(self, database: Path, cwd: Path, env: dict[str, str]) -> dict[str, Any]:
        arguments = ["--database", str(database), "--smoke-check"]
        if self.bundle is not None:
            return package_bundle.run_bundle(self.bundle, arguments, cwd, env, self.isolate_network)
        started = time.monotonic()
        try:
            # The interpreter running this tool and the repository's own launcher.
            result = subprocess.run(  # noqa: S603
                [sys.executable, str(ROOT / "inventory_desktop.py"), *arguments],
                cwd=cwd,
                env=env,
                stdin=subprocess.DEVNULL,
                capture_output=True,
                text=True,
                encoding="utf-8",
                errors="replace",
                timeout=package_bundle.RUN_TIMEOUT_SECONDS,
                check=False,
            )
        except subprocess.TimeoutExpired as exc:
            return {
                "arguments": arguments,
                "exit_code": -1,
                "seconds": package_bundle.RUN_TIMEOUT_SECONDS,
                "stdout": package_bundle._text(exc.stdout),
                "stderr": package_bundle._text(exc.stderr) + "\nTimed out.",
            }
        return {
            "arguments": arguments,
            "exit_code": result.returncode,
            "seconds": round(time.monotonic() - started, 1),
            "stdout": result.stdout,
            "stderr": result.stderr,
        }

    def describe(self) -> dict[str, Any]:
        if self.bundle is not None:
            return {"kind": "packaged-bundle", **package_bundle.bundle_record(self.bundle)}
        return {
            "kind": "source-launch",
            "python": sys.version.split()[0],
            "packages": package_bundle.recorded_versions(),
            "source": package_bundle.source_revision(ROOT),
        }


def backups_in(database: Path) -> dict[str, Path]:
    folder = database.parent / "backups"
    return (
        {path.name: path for path in sorted(folder.glob("inventory-*.db"))}
        if folder.is_dir()
        else {}
    )


def step(record: dict[str, Any], name: str, problems: list[str], **details: Any) -> bool:
    entry = {"name": name, "passed": not problems, "problems": problems, **details}
    record["steps"].append(entry)
    print(
        f"  {'pass' if not problems else 'FAIL'}  {name}"
        + "".join(f"\n        {p}" for p in problems)
    )
    return not problems


def launch_and_check(
    record: dict[str, Any],
    label: str,
    launcher: Launcher,
    database: Path,
    cwd: Path,
    env: dict[str, str],
    reference: dict[str, Any],
    original: dict[str, Any],
) -> tuple[bool, dict[str, Any], Path | None]:
    """One launch of the application on ``database``; checks what it did and backed up."""
    known = set(backups_in(database))
    run = launcher.run(database, cwd, env)
    after = snapshot(database)
    new = {name: path for name, path in backups_in(database).items() if name not in known}
    startup = [path for name, path in new.items() if "-startup" in name]
    manual = [path for name, path in new.items() if "-manual" in name]
    problems: list[str] = []
    if run["exit_code"] != 0 or "no HTTP server" not in run["stdout"]:
        problems.append(f"The launch failed (exit {run['exit_code']}): {run['stderr'][-400:]}")
    if len(startup) != 1:
        problems.append(f"Expected one new startup backup, found {len(startup)}.")
    startup_state = snapshot(startup[0]) if len(startup) == 1 else None
    if startup_state is not None:
        problems += [
            f"Startup backup: {p}" for p in compare(reference, startup_state, identical=True)
        ]
    if not manual:
        problems.append("The smoke created no manual backup.")
    manual_states = [snapshot(path) for path in manual]
    for path, state in zip(manual, manual_states, strict=True):
        problems += [f"{path.name}: {p}" for p in compare(original, state, identical=False)]
    problems += compare(original, after, identical=False)
    problems += reconcile(after)
    if len(after["tables"]["inventory_transactions"]["rows"]) <= len(
        reference["tables"]["inventory_transactions"]["rows"]
    ):
        problems.append("The workflows left no new ledger rows in the selected inventory.")
    ok = step(
        record,
        label,
        problems,
        exit_code=run["exit_code"],
        seconds=run["seconds"],
        stdout=package_bundle.excerpt(run["stdout"]),
        stderr=package_bundle.excerpt(run["stderr"]),
        startup_backups=sorted(path.name for path in startup),
        manual_backups=sorted(path.name for path in manual),
        startup_backup_identical_to_previous_state=startup_state is not None
        and not compare(reference, startup_state, identical=True),
        inventory_counts=counts(after),
        inventory_digest=digest(after),
    )
    return ok, after, startup[0] if len(startup) == 1 else None


def rehearse(
    launcher: Launcher,
    workdir: Path,
    evidence: Path,
    assets: Path = ROOT / "frontend" / "dist",
    fixture: Path = FIXTURE,
) -> bool:
    workdir, evidence = workdir.resolve(), evidence.resolve()
    if workdir.exists() and any(workdir.iterdir()):
        raise RehearsalError(f"--workdir {workdir} must be empty: the rehearsal writes real data.")
    package_bundle.require_display()
    workdir.mkdir(parents=True, exist_ok=True)
    unexpected_home = workdir / "unexpected-home"
    env = {**os.environ, "INVSYS_HOME": str(unexpected_home)}
    database = workdir / "inventory" / "inventory.db"
    cwd = workdir / "cwd"
    cwd.mkdir()
    record: dict[str, Any] = {
        "recorded_at": datetime.now(UTC).isoformat(timespec="seconds"),
        "machine": package_bundle.machine_record(),
        "application": launcher.describe(),
        "network_isolated": launcher.isolate_network,
        "fixture": {"path": fixture.name, "sha256": fixture_sha256(fixture)},
        "steps": [],
    }
    print(f"Upgrade rehearsal ({record['application']['kind']}) in {workdir}")
    install_fixture(database, fixture)
    original = snapshot(database)
    record["fixture"].update(
        counts=counts(original),
        snapshot_digest=digest(original),
        component_snapshots=component_trace(original),
        preferences={
            row[0]: row[1]
            for key, row in original["tables"]["settings"]["rows"].items()
            if key in PREFERENCE_KEYS
        },
    )
    ok = step(
        record,
        "fixture-is-intact-before-upgrade",
        [f"Fixture: {p}" for p in reconcile(original)]
        + ([] if original["integrity_check"] == "ok" else ["Fixture integrity check failed."]),
    )
    if launcher.bundle is not None:
        record["assets_verified"] = package_bundle.verify_assets(launcher.bundle, assets.resolve())

    with package_bundle.network_isolation(
        launcher.bundle or ROOT, launcher.isolate_network
    ) as isolation:
        record["network_isolation"] = isolation
        ok1, after1, pre_upgrade_backup = launch_and_check(
            record, "upgrade-open-and-workflows", launcher, database, cwd, env, original, original
        )
        ok2, after2, _ = launch_and_check(
            record, "restart-and-workflows", launcher, database, cwd, env, after1, original
        )
        ok = ok and ok1 and ok2
        rollback = restore_rollback(record, database, pre_upgrade_backup, original, after2)
        ok = ok and rollback is not None
        if rollback is not None:
            ok3, _, _ = launch_and_check(
                record,
                "reopen-after-restore-and-workflows",
                launcher,
                database,
                cwd,
                env,
                rollback,
                original,
            )
            ok = ok and ok3

    ok = (
        step(
            record,
            "nothing-written-outside-the-selected-inventory",
            [] if not unexpected_home.exists() else [f"{unexpected_home} was created."],
        )
        and ok
    )
    with tempfile.TemporaryDirectory(prefix="invsys-restore-probes-") as scratch:
        probes = restore_failure_probes(Path(scratch))
    record["restore_failure_behaviour"] = probes
    ok = (
        step(
            record,
            "restore-refusals-and-file-failures-leave-the-database-untouched",
            [f"{item['name']}: {item.get('message')}" for item in probes if not item["passed"]],
        )
        and ok
    )
    record["result"] = "passed" if ok else "failed"
    evidence.parent.mkdir(parents=True, exist_ok=True)
    evidence.write_text(json.dumps(record, indent=2) + "\n", encoding="utf-8")
    print(f"Upgrade rehearsal {record['result']}; evidence written to {evidence}")
    return ok


def restore_rollback(
    record: dict[str, Any],
    database: Path,
    oldest: Path | None,
    original: dict[str, Any],
    later: dict[str, Any],
) -> dict[str, Any] | None:
    """Restore the first launch's startup backup (the pre-upgrade state) over the later inventory."""
    problems: list[str] = []
    result: dict[str, Any] = {}
    restored: dict[str, Any] | None = None
    if oldest is None:
        problems.append("No startup backup exists to restore.")
    else:
        try:
            result = restore_from_backup(database, oldest, database.parent / "restore-aside")
        except RestoreRefused as exc:
            problems.append(str(exc))
    if oldest is not None and not problems:
        restored = snapshot(database)
        problems += [f"Restored: {p}" for p in compare(original, restored, identical=True)]
        problems += reconcile(restored)
        aside = Path(result["aside_directory"]) / database.name
        preserved = snapshot(aside)
        problems += [f"Aside copy: {p}" for p in compare(later, preserved, identical=True)]
        result["reconciliation_required"] = dropped_entries(restored, later)
        if not result["reconciliation_required"]["ledger_entries"]:
            problems.append(
                "The restore dropped no later ledger entries; the rehearsal is vacuous."
            )
    step(record, "closed-app-restore-of-the-pre-upgrade-backup", problems, **result)
    return restored if not problems else None


# ---------------------------------------------------------------- command line


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0] if __doc__ else None)
    commands = parser.add_subparsers(dest="command", required=True)
    rehearse_parser = commands.add_parser("rehearse")
    target = rehearse_parser.add_mutually_exclusive_group(required=True)
    target.add_argument("--bundle", type=Path, help="Frozen bundle to rehearse with")
    target.add_argument("--source", action="store_true", help="Rehearse with a source launch")
    rehearse_parser.add_argument("--workdir", type=Path, required=True)
    rehearse_parser.add_argument("--evidence", type=Path, required=True)
    rehearse_parser.add_argument("--assets", type=Path, default=ROOT / "frontend" / "dist")
    rehearse_parser.add_argument("--isolate-network", action="store_true")
    commands.add_parser("generate-fixture")
    args = parser.parse_args(argv)
    try:
        if args.command == "generate-fixture":
            write_fixture()
            print(f"Wrote {FIXTURE}")
            return 0
        if args.source and args.isolate_network:
            raise RehearsalError("--isolate-network applies to --bundle rehearsals only.")
        bundle = args.bundle.resolve() if args.bundle is not None else None
        launcher = Launcher(bundle, args.isolate_network)
        return 0 if rehearse(launcher, args.workdir, args.evidence, args.assets) else 1
    except (RehearsalError, package_bundle.PackagingError) as exc:
        print(f"upgrade_rehearsal: {exc}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
